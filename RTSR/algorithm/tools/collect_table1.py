"""Collect Table-I style results (model size vs PSNR) from EDSR experiment dirs.

Run from EDSR-PyTorch/ (plain python3 is enough, PyTorch not required):

    python3 tools/collect_table1.py

It scans experiment_*/config.txt (EDSR runs only), reads the best PSNR out of the
matching log.txt, recomputes the parameter count / model size from the recorded
architecture, and writes TABLE1.md in the repository root.
"""

import argparse
import glob
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from model_stats import n_params_analytic  # noqa: E402

PSNR_RE = re.compile(r'PSNR:\s*([0-9.]+)\s*\(Best:\s*([0-9.]+)\s*@epoch\s*(\d+)\)')
INT_RE = re.compile(r'\d+')

PAPER = (
    ('M1', 8, 9, 26, 33.22),
    ('M2', 8, 26, 530, 35.78),
    ('M3', 16, 64, 5362, 36.03),
)
LABEL = {(8, 9): 'M1', (8, 26): 'M2', (16, 64): 'M3'}
PERIODS = (2, 6, 30, 60)


def last_config(path):
    text = open(path, encoding='utf-8').read()
    blocks = [b for b in text.split('\n\n') if 'n_feats:' in b]
    if not blocks:
        return None
    cfg = {}
    for line in blocks[-1].splitlines():
        if ': ' in line:
            key, val = line.split(': ', 1)
            cfg[key.strip()] = val.strip()
    return cfg


def best_psnr(path):
    if not os.path.isfile(path):
        return None
    best = None
    for m in PSNR_RE.finditer(open(path, encoding='utf-8').read()):
        best_value, epoch = float(m.group(2)), int(m.group(3))
        if best is None or best_value > best[0]:
            best = (best_value, epoch)
    return best


def overhead_mbps(size_kb, period_s):
    return size_kb * 1024.0 * 8.0 / period_s / 1e6


def main():
    rows = []
    for cfg_path in sorted(glob.glob(os.path.join(ROOT, ARGS.pattern, 'config.txt'))):
        cfg = last_config(cfg_path)
        if not cfg or cfg.get('model') != 'EDSR':
            continue
        exp_dir = os.path.dirname(cfg_path)
        try:
            blocks = int(cfg.get('n_resblocks', 16))
            feats = int(cfg.get('n_feats', 64))
        except ValueError:
            continue
        scales = INT_RE.findall(cfg.get('scale', '[2]'))
        scale = int(scales[0]) if scales else 2
        psnr = best_psnr(os.path.join(exp_dir, 'log.txt'))
        n = n_params_analytic(blocks, feats, scale)
        rows.append({
            'tag': os.path.basename(exp_dir),
            'label': LABEL.get((blocks, feats), 'custom'),
            'blocks': blocks,
            'feats': feats,
            'scale': scale,
            'params': n,
            'size': n * 4 / 1024,
            'psnr': psnr[0] if psnr else None,
            'epoch': psnr[1] if psnr else None,
            'epochs': cfg.get('epochs', '?'),
            'range': cfg.get('data_range', '?'),
        })

    lines = []
    lines.append('# RTSR Table I reproduction (EDSR, x2)')
    lines.append('')
    lines.append('Generated by `tools/collect_table1.py`.')
    lines.append('')
    lines.append(ARGS.desc)
    lines.append('')
    lines.append('Absolute PSNR values are not directly comparable with the paper unless')
    lines.append('the resolution matches (paper: 1080p -> 2160p).')
    lines.append('')
    lines.append('Note: `--epochs 30` actually trains 29 epochs (`terminate()` compares')
    lines.append('`last_epoch + 1`), so the `epochs` column below is the flag, not the count.')
    lines.append('')
    lines.append('| 论文模型 | 残差块 | 特征 | 参数量 | 尺寸 (KB) | 最佳 PSNR | @epoch | epochs | data_range | 实验目录 |')
    lines.append('|---|---:|---:|---:|---:|---:|---:|---:|---|---|')

    for r in sorted(rows, key=lambda x: (x['size'], x['tag'])):
        psnr = '{:.3f}'.format(r['psnr']) if r['psnr'] is not None else '(running / failed)'
        lines.append('| {} | {} | {} | {:,.0f} | {:.0f} | {} | {} | {} | {} | `{}` |'.format(
            r['label'], r['blocks'], r['feats'], r['params'], r['size'], psnr,
            r['epoch'] if r['epoch'] is not None else '-',
            r['epochs'], r['range'], r['tag']))

    lines.append('')
    lines.append('## Paper reference (Table I)')
    lines.append('')
    lines.append('| 模型 | 残差块 | 特征 | 尺寸 (KB) | PSNR (dB) |')
    lines.append('|---|---:|---:|---:|---:|')
    for name, blocks, feats, size, psnr in PAPER:
        lines.append('| {} | {} | {} | {} | {:.2f} |'.format(name, blocks, feats, size, psnr))

    local = {}
    for r in rows:
        if r['label'] in ('M1', 'M2', 'M3') and r['psnr'] is not None:
            local[r['label']] = r

    lines.append('')
    lines.append('## 尺寸-PSNR 斜率：本地 vs 论文')
    lines.append('')
    lines.append('| 变化 | 本地尺寸倍数 | 本地 ΔPSNR | 本地每翻倍 | 论文尺寸倍数 | 论文 ΔPSNR | 论文每翻倍 |')
    lines.append('|---|---:|---:|---:|---:|---:|---:|')
    paper = {name: (size, psnr) for name, _, _, size, psnr in PAPER}
    for low, high in (('M1', 'M2'), ('M2', 'M3')):
        lr_low, lr_high = local.get(low), local.get(high)
        if not lr_low or not lr_high:
            continue
        l_ratio = lr_high['size'] / lr_low['size']
        l_delta = lr_high['psnr'] - lr_low['psnr']
        p_ratio = paper[high][0] / float(paper[low][0])
        p_delta = paper[high][1] - paper[low][1]
        lines.append('| {} -> {} | {:.1f}x | {:+.3f} | {:.3f} | {:.1f}x | {:+.2f} | {:.3f} |'.format(
            low, high, l_ratio, l_delta, l_delta / math.log(l_ratio, 2),
            p_ratio, p_delta, p_delta / math.log(p_ratio, 2)))

    lines.append('')
    lines.append('## 模型开销 vs 更新周期 ΔT（相对 10 Mbps 的 LD 视频）')
    lines.append('')
    header = '| 模型 | 尺寸 (KB) | ' + ' | '.join('ΔT={}s'.format(p) for p in PERIODS) + ' |'
    lines.append(header)
    lines.append('|---|---:|' + '---:|' * len(PERIODS))
    for name in ('M1', 'M2', 'M3'):
        r = local.get(name)
        if not r:
            continue
        cells = []
        for p in PERIODS:
            cells.append('{:.2f} Mbps / {:.0f}%'.format(
                overhead_mbps(r['size'], p), 100.0 * overhead_mbps(r['size'], p) / 10.0))
        lines.append('| {} | {:.0f} | {} |'.format(name, r['size'], ' | '.join(cells)))

    lines.append('')
    lines.append('## 偏差说明（对表时必读）')
    lines.append('')
    if ARGS.caveats:
        label, _, text = ARGS.caveats.partition('|')
        for _, item in enumerate(text.split('||'), start=1):
            lines.append('{}. {}'.format(_, item.strip()))
    else:
        lines.append('1. 见 README。')

    table = '\n'.join(lines) + '\n'
    print(table)
    out = os.path.join(ROOT, ARGS.out)
    with open(out, 'w', encoding='utf-8') as handle:
        handle.write(table)
    print('written:', out)


PARSER = argparse.ArgumentParser(description=__doc__)
PARSER.add_argument('--pattern', default='experiment_rtsr_m*')
PARSER.add_argument('--out', default='TABLE1.md')
PARSER.add_argument('--caveats', default='')
PARSER.add_argument('--desc', default='train on frames 1-400, evaluate on 401-495, i.e. **540p -> 1080p**')
ARGS = PARSER.parse_args()

if __name__ == '__main__':
    main()