"""Collect the online-training window sweep into DT_SWEEP.md."""

import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from model_stats import n_params_analytic  # noqa: E402

PSNR_RE = re.compile(r'PSNR:\s*([0-9.]+)\s*\(Best:\s*([0-9.]+)\s*@epoch\s*(\d+)\)')
WINDOW_RE = re.compile(r'1-(\d+)/')
FPS = 30.0


def best_psnr(path):
    if not os.path.isfile(path):
        return None
    best = None
    for m in PSNR_RE.finditer(open(path, encoding='utf-8').read()):
        value, epoch = float(m.group(2)), int(m.group(3))
        if best is None or value > best[0]:
            best = (value, epoch)
    return best


def last_config(path):
    text = open(path, encoding='utf-8').read()
    blocks = [b for b in text.split('\n\n') if 'n_feats:' in b]
    if not blocks:
        return None
    cfg = {}
    for line in blocks[-1].splitlines():
        if ': ' in line:
            key, val = line.split(': ', 1)
            cfg[key.strip()] = val.strip()
    return cfg


def main():
    rows = []
    for cfg_path in sorted(glob.glob(os.path.join(ROOT, 'experiment_dt_*f', 'config.txt'))):
        cfg = last_config(cfg_path)
        if not cfg:
            continue
        hit = WINDOW_RE.search(cfg.get('data_range', ''))
        if not hit:
            continue
        window = int(hit.group(1))
        feats = int(cfg.get('n_feats', 26))
        blocks = int(cfg.get('n_resblocks', 8))
        psnr = best_psnr(os.path.join(os.path.dirname(cfg_path), 'log.txt'))
        size = n_params_analytic(blocks, feats, 2) * 4 / 1024
        rows.append({
            'tag': os.path.basename(os.path.dirname(cfg_path)),
            'window': window,
            'seconds': window / FPS,
            'size': size,
            'psnr': psnr[0] if psnr else None,
            'epoch': psnr[1] if psnr else None,
        })

    lines = []
    lines.append('# 在线训练窗长（更新周期）扫描')
    lines.append('')
    lines.append('Generated by `tools/collect_dt.py`. EDSR M2 (8 blocks / 26 features),')
    lines.append('trained on frames `1-W` of the `lol_15s_1` clip, evaluated on the')
    lines.append('*later* frames 401-495 (disjoint from the training window).')
    lines.append('')
    lines.append('| 训练窗 (帧) | 折合时长 @30fps | 尺寸 (KB) | 最佳 PSNR | @epoch | 实验目录 |')
    lines.append('|---:|---:|---:|---:|---:|---|')
    for r in sorted(rows, key=lambda x: x['window']):
        psnr = '{:.3f}'.format(r['psnr']) if r['psnr'] is not None else '(running / failed)'
        lines.append('| {} | {:.1f} s | {:.0f} | {} | {} | `{}` |'.format(
            r['window'], r['seconds'], r['size'], psnr,
            r['epoch'] if r['epoch'] is not None else '-', r['tag']))

    lines.append('')
    lines.append('## 模型开销（ΔT = 窗长）')
    lines.append('')
    lines.append('| 训练窗 | ΔT | 模型开销 | 占 10 Mbps LD 预算 |')
    lines.append('|---:|---:|---:|---:|')
    for r in sorted(rows, key=lambda x: x['window']):
        mbps = r['size'] * 1024.0 * 8.0 / r['seconds'] / 1e6
        lines.append('| {} 帧 | {:.1f} s | {:.2f} Mbps | {:.0f}% |'.format(
            r['window'], r['seconds'], mbps, 100.0 * mbps / 10.0))

    lines.append('')
    lines.append('注意：只有 15 s 素材，论文的 ΔT=30-60 s 无法在这里真测，只有解析开销。')
    lines.append('另外窗长越小，模型见过的内容越少，PSNR 下降同时开销上升，两者反向 ——')
    lines.append('这正是在线训练要折中的那条曲线。')

    table = '\n'.join(lines) + '\n'
    print(table)
    out = os.path.join(ROOT, 'DT_SWEEP.md')
    open(out, 'w', encoding='utf-8').write(table)
    print('written:', out)


if __name__ == '__main__':
    main()