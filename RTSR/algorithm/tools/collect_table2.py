"""Collect Table-II style results (LD bitrate vs PSNR/VMAF) into a markdown table.

    python3 tools/collect_table2.py                       # 540p variants -> TABLE2.md
    python3 tools/collect_table2.py --pattern 'experiment_t2_4k_b*' \
        --data-dir 'dataset/4k_b{}' --out TABLE2_4K.md    # paper setting
"""

import argparse
import glob
import json
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PSNR_RE = re.compile(r'PSNR:\s*([0-9.]+)\s*\(Best:\s*([0-9.]+)\s*@epoch\s*(\d+)\)')
RATE_RE = re.compile(r'(\d+)$')

PAPER = (
    (18, 3000, 31.83, 83.55),
    (21, 3500, 32.47, 86.14),
    (24, 4000, 33.02, 87.71),
    (27, 4500, 33.48, 88.97),
    (30, 5000, 33.91, 90.09),
)


def best_psnr(path):
    if not os.path.isfile(path):
        return None
    best = None
    for m in PSNR_RE.finditer(open(path, encoding='utf-8').read()):
        value, epoch = float(m.group(2)), int(m.group(3))
        if best is None or value > best[0]:
            best = (value, epoch)
    return best


def probe(mp4):
    try:
        out = subprocess.check_output(
            ['ffprobe', '-v', 'error', '-select_streams', 'v:0',
             '-show_entries', 'stream=bit_rate', '-show_entries', 'format=size',
             '-of', 'default=nw=1', mp4], text=True)
        kbps = size = None
        for line in out.splitlines():
            if line.startswith('bit_rate='):
                kbps = int(line.split('=')[1]) / 1000.0
            elif line.startswith('size='):
                size = int(line.split('=')[1]) / (1024.0 * 1024.0)
        return kbps, size
    except Exception:
        return None, None


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--pattern', default='experiment_t2_b*')
    ap.add_argument('--out', default='TABLE2.md')
    ap.add_argument('--data-dir', default='dataset/ld_b{}')
    ap.add_argument('--general-pattern', default='experiment_t2_gen_on_b{}')
    ap.add_argument('--vmaf-json', default='vmaf_results.json')
    ap.add_argument('--desc', default=(
        '`lol_15s_1` clip, HD = 1080p, LD = 960x540 encoded with x264 2-pass; '
        'bitrates rescaled by pixel count (1/4) plus 2500 kbps as the conventional point.'))
    args = ap.parse_args()

    vmaf = {}
    vmaf_json = os.path.join(ROOT, args.vmaf_json)
    if os.path.isfile(vmaf_json):
        vmaf = json.load(open(vmaf_json, encoding='utf-8'))

    rows = []
    for d in sorted(glob.glob(os.path.join(ROOT, args.pattern))):
        tag = os.path.basename(d)
        m = RATE_RE.search(tag)
        if not m:
            continue
        rate = int(m.group(1))
        psnr = best_psnr(os.path.join(d, 'log.txt'))
        stem = os.path.basename(args.data_dir).format(rate).replace('{}', str(rate))
        mp4 = os.path.join(ROOT, args.data_dir.format(rate), '{}.mp4'.format(stem))
        kbps, size = probe(mp4)
        gen = best_psnr(os.path.join(ROOT, args.general_pattern.format(rate), 'log.txt'))
        rows.append({'rate': rate, 'kbps': kbps, 'size': size,
                     'psnr': psnr[0] if psnr else None,
                     'epoch': psnr[1] if psnr else None,
                     'gen': gen[0] if gen else None,
                     'vmaf': vmaf.get(str(rate))})

    lines = ['# RTSR Table II reproduction (LD bitrate vs quality)', '',
             'Generated by `tools/collect_table2.py`.', '', args.desc, '',
             '| LD 码率 (kbps) | 文件大小 (MB) | 专属模型 PSNR | @epoch | 通用模型 PSNR | 专属-通用 | VMAF |',
             '|---:|---:|---:|---:|---:|---:|---:|']
    for r in sorted(rows, key=lambda x: x['rate']):
        sp = '{:.3f}'.format(r['psnr']) if r['psnr'] is not None else '-'
        gp = '{:.3f}'.format(r['gen']) if r['gen'] is not None else '-'
        delta = ('{:+.3f}'.format(r['psnr'] - r['gen'])
                 if r['psnr'] is not None and r['gen'] is not None else '-')
        lines.append('| {} | {} | {} | {} | {} | {} | {} |'.format(
            '{:.0f}'.format(r['kbps']) if r['kbps'] else r['rate'],
            '{:.2f}'.format(r['size']) if r['size'] else '-',
            sp, r['epoch'] or '-', gp, delta,
            '{:.2f}'.format(r['vmaf']) if r['vmaf'] is not None else '-'))

    lines += ['', '## 论文 Table II（1080p LD, 2160p HD）', '',
              '| LD 大小 (MB) | LD 码率 (kbps) | PSNR | VMAF |',
              '|---:|---:|---:|---:|']
    for size, kbps, psnr, v in PAPER:
        lines.append('| {} | {} | {:.2f} | {:.2f} |'.format(size, kbps, psnr, v))
    lines.append('| 60 (conventional) | 10000 | 33.99 | 89.81 |')

    table = '\n'.join(lines) + '\n'
    print(table)
    out = os.path.join(ROOT, args.out)
    open(out, 'w', encoding='utf-8').write(table)
    print('written:', out)


if __name__ == '__main__':
    main()